// Contact actions (exposed globally for onclick handlers)
export const contactActions = {
    call: (phone) => {
        alert(window.t('contact.action.callMessage', { phone }));
        // In production: window.location.href = `tel:${phone}`;
    },

    sms: (phone) => {
        alert(window.t('contact.action.smsMessage', { phone }));
        // In production: window.location.href = `sms:${phone}`;
    },

    email: (email) => {
        alert(window.t('contact.action.emailMessage', { email }));
        // In production: window.location.href = `mailto:${email}`;
    }
};
